"""Battle / repo-check state machine. Transitions are enforced in code, not by a model."""
from enum import Enum


class S(str, Enum):
    CREATED = "CREATED"
    REPOSITORY_VALIDATING = "REPOSITORY_VALIDATING"
    SANDBOX_READY = "SANDBOX_READY"
    ATTACKING = "ATTACKING"
    FINDINGS_REVIEW = "FINDINGS_REVIEW"
    DEFENDING = "DEFENDING"
    AWAITING_APPROVAL = "AWAITING_APPROVAL"
    PATCHING = "PATCHING"
    RETESTING = "RETESTING"
    MANAGER_ANALYSING = "MANAGER_ANALYSING"
    # terminal
    FAILED = "FAILED"
    ATTACK_INCONCLUSIVE = "ATTACK_INCONCLUSIVE"
    NO_CONFIRMED_FINDING = "NO_CONFIRMED_FINDING"
    DEFENSE_INCONCLUSIVE = "DEFENSE_INCONCLUSIVE"
    PATCH_REJECTED = "PATCH_REJECTED"
    PATCH_FAILED = "PATCH_FAILED"
    COMPLETED = "COMPLETED"
    UNRESOLVED = "UNRESOLVED"
    INCONCLUSIVE = "INCONCLUSIVE"
    CHECK_COMPLETED = "CHECK_COMPLETED"
    CHECK_INCONCLUSIVE = "CHECK_INCONCLUSIVE"


TRANSITIONS: dict[S, set[S]] = {
    S.CREATED: {S.REPOSITORY_VALIDATING},
    S.REPOSITORY_VALIDATING: {S.SANDBOX_READY, S.FAILED},
    S.SANDBOX_READY: {S.ATTACKING, S.MANAGER_ANALYSING, S.FAILED},
    S.ATTACKING: {S.FINDINGS_REVIEW, S.ATTACK_INCONCLUSIVE},
    S.FINDINGS_REVIEW: {S.DEFENDING, S.NO_CONFIRMED_FINDING},
    S.DEFENDING: {S.AWAITING_APPROVAL, S.DEFENSE_INCONCLUSIVE},
    S.AWAITING_APPROVAL: {S.PATCHING, S.PATCH_REJECTED, S.DEFENDING},
    S.PATCHING: {S.RETESTING, S.PATCH_FAILED},
    S.RETESTING: {S.COMPLETED, S.UNRESOLVED, S.INCONCLUSIVE},
    S.MANAGER_ANALYSING: {S.CHECK_COMPLETED, S.CHECK_INCONCLUSIVE},
}

TERMINAL = {s for s in S if s not in TRANSITIONS}


class IllegalTransition(Exception):
    pass


def check(current: S, nxt: S) -> None:
    if nxt not in TRANSITIONS.get(current, set()):
        raise IllegalTransition(f"{current.value} -> {nxt.value}")
